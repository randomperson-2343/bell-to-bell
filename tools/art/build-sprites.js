#!/usr/bin/env node
// Turns the exported Aseprite sheets in art/export/ into js/art/sprite-data.js,
// the file the game actually draws from.
//
//   node tools/art/build-sprites.js          rebuild js/art/sprite-data.js
//   node tools/art/build-sprites.js --check  exit 1 if sprite-data.js is out of date
//
// Why a JS file and not the PNGs: the game opens straight from index.html with
// no server and no build, and a canvas that draws a PNG loaded from a file://
// page is "tainted" in most browsers, which breaks reading pixels back. A plain
// script loads everywhere and draws synchronously, so the first frame of every
// cutscene already has its art.
//
// Each art/export/<group>/<name>.png is a horizontal strip of frames with an
// Aseprite JSON beside it (json-array, frame tags). The sprite id is
// "<group>/<name>". Every pixel must be one of the 32 palette colours or
// transparent; anything else stops the build.
//
// The 'ui' group is page chrome (buttons, frames, icons) drawn by CSS from the
// PNGs that tools/art/build-ui.js writes to art/ui/, so it is left out here.
//
// Rows are stored run-length encoded: each run is the palette key followed by
// one character of RUN (a run of 1..64), longer runs are split.
'use strict';
const fs = require('fs');
const path = require('path');
const PNG = require('./png');
const { palette } = require('./grid');

const ROOT = path.join(__dirname, '..', '..');
const EXPORT = path.join(ROOT, 'art', 'export');
const OUT = path.join(ROOT, 'js', 'art', 'sprite-data.js');
const RUN = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';

function encodeRow(row) {
  let s = '';
  for (let i = 0; i < row.length;) {
    let j = i; while (j < row.length && row[j] === row[i] && j - i < RUN.length) j++;
    s += row[i] + RUN[j - i - 1]; i = j;
  }
  return s;
}

function build() {
  const pal = palette(), sprites = {}, problems = [];
  const groups = fs.existsSync(EXPORT) ? fs.readdirSync(EXPORT).filter((g) => g !== 'ui' && fs.statSync(path.join(EXPORT, g)).isDirectory()).sort() : [];
  for (const g of groups) {
    for (const f of fs.readdirSync(path.join(EXPORT, g)).filter((f) => f.endsWith('.png')).sort()) {
      const name = f.slice(0, -4), id = `${g}/${name}`, jsonPath = path.join(EXPORT, g, name + '.json');
      if (!fs.existsSync(jsonPath)) { problems.push(`${id}: no ${name}.json beside the PNG`); continue; }
      const meta = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
      const img = PNG.read(fs.readFileSync(path.join(EXPORT, g, f)));
      const list = Array.isArray(meta.frames) ? meta.frames : Object.keys(meta.frames).map((k) => meta.frames[k]);
      const tags = (meta.meta && meta.meta.frameTags) || [];
      const frames = {}, order = [];
      list.forEach((fr, i) => {
        const r = fr.frame, rows = [];
        for (let y = 0; y < r.h; y++) {
          let row = '';
          for (let x = 0; x < r.w; x++) {
            const o = ((r.y + y) * img.w + r.x + x) * 4;
            if (img.px[o + 3] < 128) { row += '.'; continue; }
            const k = pal.byRgb[`${img.px[o]},${img.px[o + 1]},${img.px[o + 2]}`];
            if (!k) { problems.push(`${id} frame ${i} (${x},${y}): colour outside the palette`); row += '.'; continue; }
            row += k;
          }
          rows.push(encodeRow(row));
        }
        const tag = tags.find((t) => t.from === i && t.to === i);
        const key = tag ? tag.name : String(i);
        frames[key] = rows; order.push(key);
      });
      const w = list[0].frame.w, h = list[0].frame.h;
      if (list.some((fr) => fr.frame.w !== w || fr.frame.h !== h)) problems.push(`${id}: frames differ in size`);
      sprites[id] = { w, h, order, frames };
    }
  }
  if (problems.length) { console.error(problems.slice(0, 40).join('\n')); process.exit(1); }
  const body = Object.keys(sprites).map((id) => {
    const s = sprites[id];
    const fr = s.order.map((k) => `      ${JSON.stringify(k)}: [\n${s.frames[k].map((r) => '        ' + JSON.stringify(r)).join(',\n')}\n      ]`).join(',\n');
    return `    ${JSON.stringify(id)}: { w: ${s.w}, h: ${s.h}, frames: {\n${fr}\n    } }`;
  }).join(',\n');
  return `// GENERATED by tools/art/build-sprites.js from art/export/. Do not edit by hand:
// change the .aseprite in art/src/, export it (node tools/art/pack.js --export-all), which rebuilds this file.
// Rows are run-length encoded: a palette key, then one character of the run alphabet (a run of 1..64).
(function (B) {
  'use strict';
  const RUN = ${JSON.stringify(RUN)};
  const RAW = {
${body}
  };
  const cache = {};
  function decode(rows) {
    return rows.map((r) => { let s = ''; for (let i = 0; i < r.length; i += 2) s += r[i].repeat(RUN.indexOf(r[i + 1]) + 1); return s; });
  }
  // B.Art.get(id, frame) -> { w, h, rows } (rows of palette keys, as B.Pixel.sprite makes) or null.
  B.Art = {
    has: (id) => !!RAW[id],
    ids: () => Object.keys(RAW),
    frames: (id) => (RAW[id] ? Object.keys(RAW[id].frames) : []),
    get(id, frame) {
      const s = RAW[id]; if (!s) return null;
      const f = frame == null ? Object.keys(s.frames)[0] : String(frame);
      if (!s.frames[f]) return null;
      const k = id + '#' + f;
      return cache[k] || (cache[k] = { w: s.w, h: s.h, rows: decode(s.frames[f]) });
    }
  };
})(window.BTB);
`;
}

if (require.main === module) {
  const js = build();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== js) { console.error('js/art/sprite-data.js is out of date: run node tools/art/build-sprites.js'); process.exit(1); }
    console.log('sprite-data.js is up to date');
  } else { fs.writeFileSync(OUT, js); console.log('wrote ' + path.relative(ROOT, OUT) + ' (' + js.length + ' bytes)'); }
}
module.exports = { build, encodeRow, RUN };
