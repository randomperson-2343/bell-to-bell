// Packs the music kit (events/*.json) into the two plain-script data files the
// game loads. The game runs from file:// with no build step, so JSON cannot be
// fetched; it has to ship as JS.
//
//   node tools/build-audio-data.js [path-to-kit-events]
//
// With no argument it reads docs/music-kit/events, the copy of the kit kept in
// this repo.
//
// Writes js/audio/music-data.js and js/audio/sfx-pack.js. Everything is
// deterministic: the same kit always produces the same two files. Events are
// stored as tuples [t, d, n, v, instrument, layer, pan, extras] to keep the
// scores small; music-engine.js unpacks them.
'use strict';
const fs = require('fs');
const path = require('path');

const src = process.argv[2] || path.join(__dirname, '..', 'docs', 'music-kit', 'events');
const out = path.join(__dirname, '..', 'js', 'audio');

// score key -> kit file. Keys are what the engine and the game use.
const SCORES = {
  menu: 'menu_opening_bell',
  feed1: 'feed_act1_melt_up', feed2: 'feed_act2_tremors', feed3: 'feed_act3_contagion', feed4: 'feed_act4_reckoning',
  game1: 'gameplay_act1_melt_up', game2: 'gameplay_act2_tremors', game3: 'gameplay_act3_contagion', game4: 'gameplay_act4_reckoning'
};

// The feed and menu scores were normalised after mixing in the Python render
// (handoff section 9.1). The gameplay scores carry their own mix.trackGain.
const TRACK_GAIN = { menu: 0.3572, feed1: 0.2056, feed2: 0.1875, feed3: 0.2306, feed4: 0.1455 };
// Where the anomaly ghost lives in scores that do not say (handoff 7.3).
const FEED_GHOST_LAYERS = ['melody'];

const BASE = ['t', 'd', 'n', 'v', 'i', 'l', 'p'];
const num = (x) => (x == null ? null : x);

function pack(key, file) {
  const s = JSON.parse(fs.readFileSync(path.join(src, file + '.json'), 'utf8'));
  const events = s.events.map((e, idx) => ({ e, idx }))
    .sort((a, b) => a.e.t - b.e.t || a.idx - b.idx)
    .map(({ e }) => {
      const extra = {};
      for (const k of Object.keys(e)) if (!BASE.includes(k)) extra[k] = e[k];
      const row = [e.t, e.d, num(e.n), e.v, e.i, e.l, e.p || 0];
      if (Object.keys(extra).length) row.push(extra);
      return row;
    });
  const mix = JSON.parse(JSON.stringify(s.mix));
  delete mix.intensityNote;
  if (TRACK_GAIN[key] != null) mix.trackGain = TRACK_GAIN[key];
  if (!mix.ghostLayers) mix.ghostLayers = FEED_GHOST_LAYERS;
  return {
    name: s.name, title: s.title, bpm: s.bpm, beatsPerBar: s.beatsPerBar, bars: s.bars,
    loopBeats: s.loopBeats, loopSeconds: s.loopSeconds, tonicMidi: s.tonicMidi, mode: s.mode,
    mix, events
  };
}

const HEADER = `// GENERATED by tools/build-audio-data.js from the Bell to Bell music kit.
// Do not edit by hand. Regenerate instead.
`;

function line(o) { return JSON.stringify(o); }

// ---- scores
{
  const parts = [];
  for (const key of Object.keys(SCORES)) {
    const s = pack(key, SCORES[key]);
    const { events, ...meta } = s;
    parts.push(`    ${JSON.stringify(key)}: Object.assign(${line(meta)}, {\n      events: [\n${events.map((r) => '        ' + line(r)).join(',\n')}\n      ]\n    })`);
  }
  const body = `${HEADER}(function (B) {
  'use strict';
  B.AudioData = B.AudioData || {};
  // Score format: events are [t (beats), d (beats), n (MIDI or null), v, instrument, layer, pan, extras?].
  B.AudioData.scores = {
${parts.join(',\n')}
  };
})(window.BTB);
`;
  fs.writeFileSync(path.join(out, 'music-data.js'), body);
}

// ---- sound effects
{
  const pk = JSON.parse(fs.readFileSync(path.join(src, 'sfx_pack.json'), 'utf8'));
  const rows = Object.keys(pk.sounds).map((id) => `    ${JSON.stringify(id)}: ${line(pk.sounds[id])}`);
  const body = `${HEADER}(function (B) {
  'use strict';
  B.AudioData = B.AudioData || {};
  // Times are seconds (the pack is a score at 60 BPM). See handoff section 6.10 for the voice types.
  B.AudioData.sfx = {
${rows.join(',\n')}
  };
  B.AudioData.sfxDuck = ${line(pk.duck)};
})(window.BTB);
`;
  fs.writeFileSync(path.join(out, 'sfx-pack.js'), body);
}
console.log('wrote js/audio/music-data.js and js/audio/sfx-pack.js');
